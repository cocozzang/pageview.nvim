#!/usr/bin/env sh
# Download the browser-side libraries listed in assets/vendor/VERSIONS.
# Files come from the npm registry through jsDelivr, pinned to exact versions.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
vendor="$root/assets/vendor"
cdn="https://cdn.jsdelivr.net/npm"

fetch() { # <package> <version> <remote path> <local path>
  mkdir -p "$(dirname "$vendor/$4")"
  curl -fsSL "$cdn/$1@$2/$3" -o "$vendor/$4"
  echo "  $4"
}

grep -v '^#' "$vendor/VERSIONS" | while read -r name version; do
  [ -n "$name" ] || continue
  echo "$name $version"
  case "$name" in
  markdown-it)
    fetch "$name" "$version" dist/browser/markdown-it.umd.min.js markdown-it/markdown-it.min.js
    fetch "$name" "$version" LICENSE markdown-it/LICENSE
    ;;
  github-markdown-css)
    fetch "$name" "$version" github-markdown.css github-markdown-css/github-markdown.css
    fetch "$name" "$version" license github-markdown-css/LICENSE
    ;;
  dompurify)
    fetch "$name" "$version" dist/purify.min.js dompurify/purify.min.js
    fetch "$name" "$version" LICENSE dompurify/LICENSE
    ;;
  @highlightjs/cdn-assets)
    # the common languages, plus Vim script
    fetch "$name" "$version" highlight.min.js highlight.js/highlight.min.js
    fetch "$name" "$version" languages/vim.min.js highlight.js/vim.min.js
    fetch "$name" "$version" styles/github.min.css highlight.js/github.min.css
    fetch "$name" "$version" styles/github-dark.min.css highlight.js/github-dark.min.css
    fetch "$name" "$version" LICENSE highlight.js/LICENSE
    ;;
  markdown-it-task-lists | markdown-it-footnote | markdown-it-emoji)
    fetch "$name" "$version" "dist/$name.min.js" "$name/$name.min.js"
    fetch "$name" "$version" LICENSE "$name/LICENSE"
    ;;
  @primer/octicons)
    # The icons of GitHub's alerts, as SVG strings in one script
    fetch "$name" "$version" LICENSE octicons/LICENSE
    {
      echo "// Generated by scripts/update-vendor.sh from $name $version"
      echo "window.pageviewOcticons = {"
      for icon in info light-bulb report alert stop; do
        svg=$(curl -fsSL "$cdn/$name@$version/build/svg/$icon-16.svg" | tr -d '\n')
        printf '  "%s": '"'"'%s'"'"',\n' "$icon" "$svg"
      done
      echo "};"
    } >"$vendor/octicons/octicons.js"
    echo "  octicons/octicons.js"
    ;;
  katex)
    fetch "$name" "$version" dist/katex.min.js katex/katex.min.js
    fetch "$name" "$version" dist/katex.min.css katex/katex.min.css
    fetch "$name" "$version" LICENSE katex/LICENSE
    # every font, but only as woff2: Chromium never asks for the others
    rm -rf "$vendor/katex/fonts"
    curl -fsSL "https://data.jsdelivr.com/v1/packages/npm/$name@$version?structure=flat" |
      grep -o '"/dist/fonts/[^"]*\.woff2"' | tr -d '"' | while read -r font; do
      fetch "$name" "$version" "${font#/}" "katex/${font#/dist/}"
    done
    ;;
  markdown-it-texmath)
    fetch "$name" "$version" texmath.js markdown-it-texmath/texmath.js
    fetch "$name" "$version" license.txt markdown-it-texmath/LICENSE
    ;;
  mermaid)
    fetch "$name" "$version" dist/mermaid.min.js mermaid/mermaid.min.js
    fetch "$name" "$version" LICENSE mermaid/LICENSE
    ;;
  *)
    echo "unknown package: $name" >&2
    exit 1
    ;;
  esac
done
